CREATE TABLE public.tblgroup (
    fldgroupid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    fldgroupname character varying(255) NOT NULL,
    fldcreatedby bigint,
    fldupdatedby bigint,
    fldcreatedat timestamp without time zone,
    fldupdatedat timestamp without time zone
) TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.tblgroup
    OWNER to postgres;


CREATE TABLE public.tblpersongroup (
    fldpersongroupid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fldgroupid bigint NOT NULL,
    fldpersonid bigint NOT NULL,
    fldcreatedby bigint,
    fldupdatedby bigint,
    fldcreatedat timestamp without time zone,
    fldupdatedat timestamp without time zone,
    CONSTRAINT fk_tblpersongroup_groupid FOREIGN KEY (fldgroupid)
        REFERENCES public.tblgroup (fldgroupid) MATCH SIMPLE
        ON UPDATE CASCADE
        ON DELETE CASCADE
        NOT VALID,
    CONSTRAINT fk_tblpersongroup_personid FOREIGN KEY (fldpersonid)
        REFERENCES public.tblperson (fldpersonid) MATCH SIMPLE
        ON UPDATE CASCADE
        ON DELETE CASCADE
        NOT VALID
) TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.tblpersongroup
    OWNER to postgres;